SUP = str.maketrans("-0123456789", "⁻⁰¹²³⁴⁵⁶⁷⁸⁹")


def n(v):
    return f"{v:,.0f}"


def f3(v):
    return f"{v:.3f}"


def f2(v):
    return f"{v:.2f}"


def pct(v, d=1):
    return f"{100 * v:.{d}f} %"


def ci(c, d=3):
    return f"{c[0]:.{d}f} to {c[1]:.{d}f}"


def pv(p):
    if p >= 0.01:
        return f"{p:.2f}"
    m, e = f"{p:.0e}".split("e")
    return f"{m}·10{str(int(e)).translate(SUP)}"


def rate(c):
    return f"{n(c['caught'])} ({pct(c['share'])})"


